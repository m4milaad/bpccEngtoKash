"""
KATHE 2026 — Offline Validation Benchmark & Leaderboard Score Predictor
Evaluate fine-tuned models directly against ground-truth validation data (data/bpcc/val.csv)
to get your exact predicted competition score (sqrt(BLEU * chrF++)) before submitting to Kaggle.

Usage (IndicTrans2):
    python eval_validation.py --model_type indictrans2 --model_path models/indictrans2-best --num_beams 4

Usage (NLLB):
    python eval_validation.py --model_type nllb --model_path models/best --num_beams 4

Usage (Fast check on 100 samples):
    python eval_validation.py --limit 100
"""

